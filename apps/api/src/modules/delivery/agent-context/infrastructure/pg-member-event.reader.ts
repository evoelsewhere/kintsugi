// PostgreSQL adapter for the retained, project-sequenced member event log.

import { Injectable } from "@nestjs/common";
import { MEMBER_SCHEMA_VERSION, taskEventSchema } from "@kintsugi/harness-sdk";
import { getPool } from "#common/db/pool.js";
import { MemberEventReader, type MemberEventEnvelope } from "../domain/member-event.port.js";

interface MemberEventRow {
  id: string;
  project_id: string;
  sequence: string;
  unit_id: string;
  kind: string;
  metadata: unknown;
  created_at: Date | string;
}

const POSTGRES_UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

@Injectable()
export class PgMemberEventReader extends MemberEventReader {
  async latestSequence(projectId: string): Promise<string> {
    const result = await getPool().query<{ last_sequence: string }>(
      "select coalesce((select last_sequence::text from workflow.member_event_cursor where project_id = $1), '0') as last_sequence",
      [projectId],
    );
    return result.rows[0]?.last_sequence ?? "0";
  }

  async resolveCursor(projectId: string, unitId: string, eventId: string): Promise<string | undefined> {
    // Event ids are UUIDs generated by the outbox writer. Reject malformed opaque
    // client cursors as expired instead of letting PostgreSQL raise an invalid-UUID error.
    if (!POSTGRES_UUID.test(eventId)) return undefined;
    const result = await getPool().query<{ sequence: string }>(
      `select sequence::text as sequence
       from workflow.member_event
       where id = $1 and project_id = $2 and unit_id = $3
         and created_at >= now() - interval '7 days'
       limit 1`,
      [eventId, projectId, unitId],
    );
    return result.rows[0]?.sequence;
  }

  async readAfter(projectId: string, unitId: string, sequence: string, limit: number): Promise<MemberEventEnvelope[]> {
    if (!Number.isSafeInteger(limit) || limit < 1 || limit > 100) throw new TypeError("member event batch limit must be between 1 and 100");
    const result = await getPool().query<MemberEventRow>(
      `select id::text, project_id, sequence::text as sequence, unit_id, kind, metadata, created_at
       from workflow.member_event
       where project_id = $1 and unit_id = $2 and sequence > $3::bigint
         and created_at >= now() - interval '7 days'
       order by sequence asc
       limit $4`,
      [projectId, unitId, sequence, limit],
    );
    return result.rows.map((row) => {
      const occurredAt = row.created_at instanceof Date ? row.created_at.toISOString() : new Date(row.created_at).toISOString();
      const event = taskEventSchema.parse({
        schemaVersion: MEMBER_SCHEMA_VERSION,
        id: row.id,
        projectId: row.project_id,
        unitId: row.unit_id,
        kind: row.kind,
        occurredAt,
        metadata: row.metadata,
      });
      return { event, sequence: row.sequence };
    });
  }
}
