// The installers an installation serves at /api/v1/releases/latest/install.sh and install.ps1 (ADR-0070).
// Each script has the installation's URL, the version and the SHA-256 of every package written into it, so the
// download is checked against a hash that came with the script. Nothing is run as an administrator and nothing
// outside the install folder is changed, except the user's PATH on Windows (a User-scope variable, as installers do).

import type { ReleaseManifest } from "../domain/release.js";

export interface InstallScriptInput {
  /** The installation's canonical URL (KINTSUGI_PUBLIC_URL). */
  baseUrl: string;
  manifest: ReleaseManifest;
}

const shQuote = (value: string): string => `'${value.replaceAll("'", "'\\''")}'`;
const psQuote = (value: string): string => `'${value.replaceAll("'", "''")}'`;

export function renderInstallSh({ baseUrl, manifest }: InstallScriptInput): string {
  const unix = manifest.assets.filter((asset) => asset.platform.startsWith("linux-") || asset.platform.startsWith("darwin-"));
  const lines = [
    "#!/bin/sh",
    "# Installs the Kintsugi CLI from this installation. Generated by Kintsugi: the download is checked against",
    "# the SHA-256 below, the CLI goes to ~/.kintsugi (KINTSUGI_HOME) and nothing else is changed.",
    "set -eu",
    "",
    `BASE_URL=${shQuote(baseUrl)}`,
    `VERSION=${shQuote(manifest.version)}`,
    `MIN_NODE=${shQuote(manifest.minNode)}`,
    "",
    "say() { printf '%s\\n' \"$*\"; }",
    "fail() { printf 'kintsugi install: %s\\n' \"$*\" >&2; exit 1; }",
    "",
    "case \"$(uname -s)\" in",
    "  Linux) os=linux ;;",
    "  Darwin) os=darwin ;;",
    "  *) fail \"unsupported operating system $(uname -s); download a package from $BASE_URL/guideline/install-the-cli\" ;;",
    "esac",
    "case \"$(uname -m)\" in",
    "  x86_64 | amd64) arch=x64 ;;",
    "  arm64 | aarch64) arch=arm64 ;;",
    "  *) fail \"unsupported CPU $(uname -m); download a package from $BASE_URL/guideline/install-the-cli\" ;;",
    "esac",
    "case \"$os-$arch\" in",
    ...unix.map((asset) => `  ${asset.platform}) file=${shQuote(asset.file)}; sha256=${shQuote(asset.sha256)} ;;`),
    "  *) fail \"this installation has no CLI package for $os-$arch\" ;;",
    "esac",
    "",
    "command -v node >/dev/null 2>&1 || fail \"Node.js $MIN_NODE or newer is required; install it from https://nodejs.org and run this again\"",
    "node -e 'const need = process.argv[1].split(\".\").map(Number), have = process.versions.node.split(\".\").map(Number); for (let i = 0; i < 3; i++) { if (have[i] > need[i]) process.exit(0); if (have[i] < need[i]) process.exit(1); }' \"$MIN_NODE\" \\",
    "  || fail \"Node.js $MIN_NODE or newer is required (found $(node --version)); update it and run this again\"",
    "command -v tar >/dev/null 2>&1 || fail \"tar is required\"",
    "",
    "download() {",
    "  if command -v curl >/dev/null 2>&1; then curl -fsSL -o \"$2\" \"$1\"",
    "  elif command -v wget >/dev/null 2>&1; then wget -qO \"$2\" \"$1\"",
    "  else fail \"curl or wget is required\"; fi",
    "}",
    "sha256_of() {",
    "  if command -v sha256sum >/dev/null 2>&1; then sha256sum \"$1\" | cut -d ' ' -f 1",
    "  elif command -v shasum >/dev/null 2>&1; then shasum -a 256 \"$1\" | cut -d ' ' -f 1",
    "  elif command -v openssl >/dev/null 2>&1; then openssl dgst -sha256 \"$1\" | sed 's/^.*= //'",
    "  else fail \"sha256sum, shasum or openssl is required to check the download\"; fi",
    "}",
    "",
    "home=${KINTSUGI_HOME:-$HOME/.kintsugi}",
    "tmp=$(mktemp -d \"${TMPDIR:-/tmp}/kintsugi-install.XXXXXX\")",
    "trap 'rm -rf \"$tmp\"' EXIT",
    "",
    "say \"Downloading the Kintsugi CLI $VERSION for $os-$arch\"",
    "download \"$BASE_URL/api/v1/releases/$VERSION/$file\" \"$tmp/$file\"",
    "[ \"$(sha256_of \"$tmp/$file\")\" = \"$sha256\" ] || fail \"the download does not match its checksum; nothing was installed\"",
    "tar -xzf \"$tmp/$file\" -C \"$tmp\"",
    "[ -f \"$tmp/kintsugi/lib/kintsugi.mjs\" ] || fail \"the package is incomplete; nothing was installed\"",
    "",
    "mkdir -p \"$home/bin\"",
    "rm -rf \"$home/app.old\"",
    "if [ -d \"$home/app\" ]; then mv \"$home/app\" \"$home/app.old\"; fi",
    "mv \"$tmp/kintsugi\" \"$home/app\" 2>/dev/null || { cp -R \"$tmp/kintsugi\" \"$home/app\" && rm -rf \"$tmp/kintsugi\"; }",
    "rm -rf \"$home/app.old\"",
    "printf '#!/bin/sh\\nexec \"%s/app/bin/kintsugi\" \"$@\"\\n' \"$home\" > \"$home/bin/kintsugi\"",
    "chmod 755 \"$home/bin/kintsugi\"",
    "printf '{\"baseUrl\":\"%s\"}\\n' \"$BASE_URL\" > \"$home/install.json\"",
    "",
    "say \"Installed the Kintsugi CLI $(\"$home/bin/kintsugi\" --version) in $home\"",
    "case \":$PATH:\" in",
    "  *\":$home/bin:\"*) ;;",
    "  *) say \"Add it to your PATH, then run: kintsugi --version\"; say \"  export PATH=\\\"$home/bin:\\$PATH\\\"\" ;;",
    "esac",
    "",
  ];
  return lines.join("\n");
}

export function renderInstallPs1({ baseUrl, manifest }: InstallScriptInput): string {
  const windows = manifest.assets.filter((asset) => asset.platform.startsWith("win32-"));
  const lines = [
    "# Installs the Kintsugi CLI from this installation. Generated by Kintsugi: the download is checked against",
    "# the SHA-256 below, the CLI goes to %LOCALAPPDATA%\\Kintsugi (KINTSUGI_HOME) and its bin folder is added to your",
    "# user PATH. Nothing needs administrator rights.",
    "$ErrorActionPreference = 'Stop'",
    "$ProgressPreference = 'SilentlyContinue'",
    "[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12",
    "",
    `$BaseUrl = ${psQuote(baseUrl)}`,
    `$Version = ${psQuote(manifest.version)}`,
    `$MinNode = ${psQuote(manifest.minNode)}`,
    "$Packages = @{",
    ...windows.map((asset) => `  ${psQuote(asset.platform)} = @{ File = ${psQuote(asset.file)}; Sha256 = ${psQuote(asset.sha256)} }`),
    "}",
    "",
    "function Fail($message) { throw \"kintsugi install: $message\" }",
    "",
    "$cpu = [System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()",
    "switch ($cpu) {",
    "  'X64' { $platform = 'win32-x64' }",
    "  'Arm64' { $platform = 'win32-arm64' }",
    "  default { Fail \"unsupported CPU $cpu; download a package from $BaseUrl/guideline/install-the-cli\" }",
    "}",
    "$package = $Packages[$platform]",
    "if (-not $package) { Fail \"this installation has no CLI package for $platform\" }",
    "",
    "if (-not (Get-Command node -ErrorAction SilentlyContinue)) { Fail \"Node.js $MinNode or newer is required; install it from https://nodejs.org and run this again\" }",
    "$haveNode = [version]((& node -p 'process.versions.node').Trim())",
    "if ($haveNode -lt [version]$MinNode) { Fail \"Node.js $MinNode or newer is required (found $haveNode); update it and run this again\" }",
    "$tar = Join-Path $env:SystemRoot 'System32\\tar.exe'",
    "if (-not (Test-Path $tar)) { $found = Get-Command tar -ErrorAction SilentlyContinue; if ($found) { $tar = $found.Source } else { Fail 'tar.exe is required (it ships with Windows 10 and later)' } }",
    "",
    "$KintsugiHome = if ($env:KINTSUGI_HOME) { $env:KINTSUGI_HOME } else { Join-Path $env:LOCALAPPDATA 'Kintsugi' }",
    "$work = Join-Path ([System.IO.Path]::GetTempPath()) ('kintsugi-install-' + [guid]::NewGuid().ToString('N'))",
    "New-Item -ItemType Directory -Path $work | Out-Null",
    "try {",
    "  Write-Host \"Downloading the Kintsugi CLI $Version for $platform\"",
    "  $archive = Join-Path $work $package.File",
    "  Invoke-WebRequest -UseBasicParsing -Uri \"$BaseUrl/api/v1/releases/$Version/$($package.File)\" -OutFile $archive",
    "  $hash = (Get-FileHash -Algorithm SHA256 -Path $archive).Hash.ToLowerInvariant()",
    "  if ($hash -ne $package.Sha256) { Fail 'the download does not match its checksum; nothing was installed' }",
    "  & $tar -xzf $archive -C $work",
    "  if ($LASTEXITCODE -ne 0) { Fail 'could not unpack the package; nothing was installed' }",
    "  if (-not (Test-Path (Join-Path $work 'kintsugi\\lib\\kintsugi.mjs'))) { Fail 'the package is incomplete; nothing was installed' }",
    "",
    "  $app = Join-Path $KintsugiHome 'app'",
    "  $bin = Join-Path $KintsugiHome 'bin'",
    "  New-Item -ItemType Directory -Force -Path $bin | Out-Null",
    "  Remove-Item -Recurse -Force \"$app.old\" -ErrorAction SilentlyContinue",
    "  if (Test-Path $app) { Move-Item $app \"$app.old\" }",
    "  Move-Item (Join-Path $work 'kintsugi') $app",
    "  Remove-Item -Recurse -Force \"$app.old\" -ErrorAction SilentlyContinue",
    "  Set-Content -Path (Join-Path $bin 'kintsugi.cmd') -Encoding Ascii -Value \"@echo off`r`n`\"$app\\bin\\kintsugi.cmd`\" %*`r`n\"",
    "  Set-Content -Path (Join-Path $KintsugiHome 'install.json') -Encoding Ascii -Value (ConvertTo-Json @{ baseUrl = $BaseUrl } -Compress)",
    "",
    "  $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')",
    "  $entries = if ($userPath) { $userPath -split ';' | Where-Object { $_ } } else { @() }",
    "  if ($entries -notcontains $bin) { [Environment]::SetEnvironmentVariable('Path', (($entries + $bin) -join ';'), 'User'); Write-Host \"Added $bin to your user PATH; open a new terminal to use it.\" }",
    "  if (($env:Path -split ';') -notcontains $bin) { $env:Path = \"$env:Path;$bin\" }",
    "",
    "  Write-Host \"Installed Kintsugi CLI $(& (Join-Path $bin 'kintsugi.cmd') --version) in $KintsugiHome\"",
    "} finally {",
    "  Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue",
    "}",
    "",
  ];
  return lines.join("\r\n");
}
